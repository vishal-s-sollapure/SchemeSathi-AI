from typing import Any, Dict, List, Optional
from pydantic import BaseModel, ConfigDict, Field


class DocumentChunk(BaseModel):
    """Atomic evidence chunk preserved with authoritative government metadata."""
    chunk_id: str
    text: str
    document_title: str
    scheme_id: Optional[str] = None
    official_source_url: str
    government_department: str
    page_number: Optional[str] = None
    section_or_clause: str
    applicable_cycle: str
    verification_status: str = "VERIFIED"
    metadata: Dict[str, Any] = Field(default_factory=dict)
    embedding: Optional[List[float]] = None

    model_config = ConfigDict(from_attributes=True)


class RetrievalResult(BaseModel):
    """Result of hybrid document retrieval."""
    query: str
    normalized_query: str
    chunks: List[DocumentChunk]
    scores: List[float]
    sufficient_evidence: bool = True
    retrieval_strategy: str = "hybrid_dense_lexical"


class ValidatedCitation(BaseModel):
    """Citation verified to originate strictly from retrieved official evidence."""
    source_title: str
    circular_number: Optional[str] = None
    clause_or_section: str
    page_number: Optional[str] = None
    official_source_url: str
    verification_status: str = "OFFICIALLY_VERIFIED"
    matched_chunk_id: str
    excerpt: str


class RAGResponse(BaseModel):
    """Final grounded response generated by SchemeSathi RAG engine."""
    query: str
    answer: str
    language: str = "en"
    citations: List[ValidatedCitation] = Field(default_factory=list)
    confidence_score: float = Field(..., ge=0.0, le=1.0)
    is_grounded: bool = True
    sufficient_evidence: bool = True
    suggested_follow_ups: List[str] = Field(default_factory=list)
    official_disclaimer: str = (
        "Grounding Guarantee: Factual claims are strictly derived from official government orders. "
        "Always verify final deadlines on the linked government portals."
    )

    model_config = ConfigDict(from_attributes=True)
